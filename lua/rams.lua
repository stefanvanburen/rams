local function get_terminal_colors(p)
  return {
    [0] = p.fg,
    [1] = p.accent,
    [2] = '#005523',
    [3] = '#6b5300',
    [4] = '#004c73',
    [5] = '#007373',
    [6] = '#007373',
    [7] = p.grey_ui,
    [8] = p.grey,
    [9] = p.accent,
    [10] = '#005523',
    [11] = '#6b5300',
    [12] = '#004c73',
    [13] = '#590008',
    [14] = '#007373',
    [15] = p.bg,
  }
end

function M.apply()
  vim.cmd('highlight clear')
  vim.g.colors_name = 'rams'

  local bg = vim.o.background
  local palette = palettes[bg] or palettes.light
  local groups = get_groups(palette)
  local terminal = get_terminal_colors(palette)

  for group_name, spec in pairs(groups) do
    vim.api.nvim_set_hl(0, group_name, spec)
  end

  for i = 0, 15 do
    vim.g['terminal_color_' .. i] = terminal[i]
  end
end

return M
